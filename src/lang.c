const char *tr(int id)
{
    if (id < 0 || id >= NUM_STRINGS)
        return "";
    return strings[g_lang][id];
}

const char *rules_line(int page, int line)
{
    return rules[g_lang][page][line];
}

const char *lang_name(int lang)
{
    static const char *const names[NUM_LANGS] = { "PORTUGUES", "ENGLISH", "ESPANOL" };
    return names[lang];
}
